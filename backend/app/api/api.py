
from fastapi import APIRouter, UploadFile, File, HTTPException, Body
import os
import pdfplumber
import docx
import openai
from dotenv import load_dotenv
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
import uuid
import json

router = APIRouter()

@router.post("/generate-scripts")
async def generate_scripts(course_json: dict = Body(...)):
    """
    Receives the JSON generated by the AI with the course and generates a detailed spoken script PDF for each lesson using the AI.
    Returns the names of the generated PDFs.
    """
    if not course_json.get("lessons"):
        raise HTTPException(status_code=400, detail="No lessons found in input JSON.")

    pdf_links = []
    for idx, lesson in enumerate(course_json["lessons"], 1):
        lesson_title = lesson.get("lesson", f"Lesson {idx}")
        topics = lesson.get("topics", [])
        # Prompt for the AI to generate the spoken script
        script_prompt = (
            f"You are an expert teacher. Generate a detailed spoken script for the lesson titled '{lesson_title}'. "
            f"Explain the following topics clearly and in a didactic way: {', '.join(topics)}. "
            "The script should be ready to be read in an educational video, with an introduction, development, and closing."
        )
        try:
            client = openai.OpenAI(api_key=openai.api_key)
            response = client.chat.completions.create(
                model="gpt-3.5-turbo",
                messages=[{"role": "user", "content": script_prompt}]
            )
            script_text = response.choices[0].message.content
        except Exception as e:
            raise HTTPException(status_code=500, detail=f"Error generating script for lesson '{lesson_title}': {str(e)}")

        # Generate PDF
        pdf_filename = f"script_{uuid.uuid4().hex[:8]}_{idx}.pdf"
        pdf_path = os.path.join(UPLOAD_FOLDER, pdf_filename)
        c = canvas.Canvas(pdf_path, pagesize=letter)
        width, height = letter
        c.setFont("Helvetica-Bold", 14)
        c.drawString(40, height - 50, f"Lesson Script: {lesson_title}")
        c.setFont("Helvetica", 11)
        y = height - 80
        for line in script_text.split('\n'):
            if y < 60:
                c.showPage()
                y = height - 50
                c.setFont("Helvetica", 11)
            c.drawString(40, y, line.strip())
            y -= 16
        c.save()
        pdf_links.append({"lesson": lesson_title, "pdf": pdf_filename})

    return {"scripts": pdf_links}



load_dotenv(os.path.join(os.path.dirname(__file__), '../../.env'))
